"""NYS DEC Environmental Notice Bulletin (ENB) -> Agenda Ahead items (gated, data/test/notices).

The ENB is the state's weekly bulletin (Wednesdays) of permit applications, SEQR determinations, hearings and
comment periods: https://dec.ny.gov/news/environmental-notice-bulletin. Each notice is its own page under
/news/environmental-notice-bulletin/<issue date>/[seqr|completed-application|public-notice/]<town>-<project>,
titled "Town of X - Project". The SEQR notices are the useful ones for us: a town board or planning board,
as lead agency, says what it is deciding (a solar array, a battery system, a zoning law) before it votes.

What is read (plain GETs through watch351.fetch.PoliteFetcher):
  * the sitemap index https://dec.ny.gov/sitemap.xml and its pages, for the notice URLs of the last weeks
    (the bulletin's own listing page is the one path dec.ny.gov's robots.txt disallows; the notice pages
    and the sitemaps are allowed, and this module asks the fetcher before every request)
  * each notice page in the window

Not read: nothing is posted, no search form is used. The sitemap is regenerated by the site on its own
schedule (its lastmod ran about two weeks behind the newest issue on 2026-11-06), so the newest issue can
reach us a week or two late.

Item: title, publish date, kind (seqr / completed_application / public_notice / permit_notice), category
(the notice's first line: "Negative Declaration", "Notice of Completed Application", ...), municipality as
named and as resolved to the site's name, county, DEC region, lead agency or applicant, description,
permits applied for, comment deadline, hearing date and place when the notice gives one, topics, link.

Hit (source_kind "public_notice"): one per relevant notice filed under the municipality in the title, board
"NYS DEC Environmental Notice Bulletin", meeting_date = hearing date, else comment deadline, else null
(a SEQR determination has no date of its own).

    cd projects/351watch/crawler
    python3 -m watch351.sources.ny_enb --days 30
    python3 -m watch351.sources.ny_enb --offline        # rebuild from the fetch cache only
"""

from __future__ import annotations

import argparse
import logging
import re
import sys
from collections import Counter
from datetime import date
from pathlib import Path

from bs4 import BeautifulSoup

from ..fetch import DEFAULT_CACHE_DIR, FetchError, PoliteFetcher, RobotsDisallowed
from .notice_feeds import (DEFAULT_OUT, NYPlaces, check_out_dir, county_named, iso, load_ledger, make_hit,
                           municipalities, network_report, notice_topics, parse_date, parse_dates, sentences,
                           snippet_of, window_start, write_outputs)
from .state_feeds import clean, first_seen, now_iso

log = logging.getLogger("ny_enb")

SOURCE = "ny_enb"
SOURCE_KIND = "public_notice"
STATE = "NY"
BOARD = "NYS DEC Environmental Notice Bulletin"
SITEMAP_INDEX = "https://dec.ny.gov/sitemap.xml"
LISTING_URL = "https://dec.ny.gov/news/environmental-notice-bulletin"
ENB_PATH = "/news/environmental-notice-bulletin/"
SITEMAP_MAX_AGE = 20 * 3600
NOTICE_MAX_AGE = None          # a notice page does not change once published
MAX_NOTICES_PER_RUN = 400      # a backfill of several weeks at one request a second is a few minutes

_ENB_URL = re.compile(r"<loc>(https://dec\.ny\.gov" + re.escape(ENB_PATH) + r"(\d{4}-\d{2}-\d{2})/([^<]+))</loc>"
                      r"(?:\s*<lastmod>([^<]+)</lastmod>)?")
_SITEMAP_PAGE = re.compile(r"<loc>(https://dec\.ny\.gov/sitemap\.xml\?page=\d+)</loc>(?:\s*<lastmod>([^<]+)</lastmod>)?")
_TITLE_MUNI = re.compile(r"^(Towns?|Cit(?:y|ies)|Villages?)\s+of\s+(.+?)\s+[-–]\s+(.*)$", re.S)
_TITLE_OTHER = re.compile(r"^(Bronx|Brooklyn|Queens|Manhattan|Staten Island|Statewide|New York City|"
                          r"Multiple (?:Counties|Towns|Municipalities)|[A-Z][a-z]+ County)\s+[-–]\s+(.*)$", re.S)
_LEAD_AGENCY = re.compile(r"^(?:[A-Z][a-z]+\s+County\s*[-–]\s*)?(?:The\s+)?(.{3,120}?),\s+as\s+lead\s+agency", re.S)
_HEARING = re.compile(r"((?:public|legislative|adjudicatory|issues\s+conference|informational)\s+(?:comment\s+)?hearing"
                      r"[^.]{0,260})", re.I)
_PLACE = re.compile(r"\b(?:held|located|take\s+place|convene)\s+(?:virtually\s+)?(?:at|in)\s+(?:the\s+)?([^.;]{5,140}?)"
                    r"(?:\s+(?:on|at)\s+(?:\d|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday)|[.;]|$)", re.I)
_DEADLINE_LINE = re.compile(r"(?:deadline\s+for\s+(?:written\s+)?comments?|comment\s+(?:period\s+)?(?:ends|deadline)|"
                            r"comments?\s+(?:are\s+)?due|comments?\b[^.]{0,40}?\s+(?:must|should|may)\s+be\s+(?:submitted|received|"
                            r"postmarked|sent|filed)[^.]{0,60}?(?:by|no\s+later\s+than|on\s+or\s+before|until)|"
                            r"written\s+comments?[^.]{0,80}?(?:by|no\s+later\s+than|until|on\s+or\s+before)|"
                            r"accepted\s+(?:through|until))\s*:?\s*([^.;\n]{0,80})", re.I)
_LABELS = ("Applicant", "Facility", "Application ID", "Permit(s) Applied for", "Project is Located", "Project Description",
           "Permittee Name", "Facility Name", "Facility Address", "Facility Type", "(C)ity, (T)own, or (V)illage",
           "Deadline for Comments", "Dec Number", "SPDES Number", "Receiving Waters", "County", "Location",
           "Comment Period Ends", "Project Title", "APA Project Number", "APA Land Use Classification", "Lead Agency",
           "Hearing Date", "Hearing Location", "Written Comments Due", "Contact for this Project", "Office", "APA Contact",
           "Ranking Score", "Water Classification", "Type of Waste/Flow Rate", "Project Location", "Project Name")


def kind_of(url: str) -> str:
    rest = url.split(ENB_PATH, 1)[1].split("/", 1)[1] if ENB_PATH in url else ""
    if rest.startswith("seqr/"):
        return "seqr"
    if rest.startswith("completed-application/"):
        return "completed_application"
    if rest.startswith("public-notice/"):
        return "public_notice"
    return "permit_notice"


# ------------------------------------------------------------------------------------------ sitemaps
def sitemap_pages(fetcher: PoliteFetcher) -> list[tuple[str, str]]:
    with fetcher.purpose("listing"):
        r = fetcher.get(SITEMAP_INDEX, max_age=SITEMAP_MAX_AGE)
    if not r.ok:
        raise FetchError(f"sitemap index HTTP {r.status}")
    return [(m.group(1), m.group(2) or "") for m in _SITEMAP_PAGE.finditer(r.text)]


def notice_urls(fetcher: PoliteFetcher, since: date, errors: list[str]) -> list[tuple[str, date, str]]:
    """(url, issue date, lastmod) for every ENB notice dated `since` or later, from every sitemap page."""
    out: dict[str, tuple[str, date, str]] = {}
    for page, _lastmod in sitemap_pages(fetcher):
        try:
            with fetcher.purpose("listing"):
                r = fetcher.get(page, max_age=SITEMAP_MAX_AGE)
        except FetchError as e:
            errors.append(f"sitemap {page}: {e}"[:200])
            continue
        if not r.ok:
            errors.append(f"sitemap {page}: HTTP {r.status}")
            continue
        for m in _ENB_URL.finditer(r.text):
            url, issue, slug, lastmod = m.group(1), m.group(2), m.group(3), m.group(4) or ""
            if slug.startswith("help") or "/" not in url:
                continue
            try:
                d = date.fromisoformat(issue)
            except ValueError:
                continue
            if d >= since:
                out[url] = (url, d, lastmod)
    return sorted(out.values(), key=lambda t: (t[1], t[0]))


# ------------------------------------------------------------------------------------------ one notice
def _text_lines(node) -> list[str]:
    txt = node.get_text("\n")
    return [clean(line) for line in txt.split("\n") if clean(line)]


def parse_notice(html: str, url: str) -> dict:
    soup = BeautifulSoup(html, "lxml")
    main = soup.find("main") or soup
    for t in main(["script", "style", "nav", "header", "footer"]):
        t.decompose()
    h1 = main.find("h1")
    title = clean(h1.get_text(" ")) if h1 else ""
    hero = main.find("div", class_=re.compile(r"c-hero-basic"))
    pub = parse_date(re.search(r"ENB Publish Date:?\s*([\d/]+)", hero.get_text(" ") if hero else "").group(1)
                     if hero and re.search(r"ENB Publish Date:?\s*([\d/]+)", hero.get_text(" ")) else "")
    body = main.find("div", class_="l-sidebar__main") or main
    for t in body.find_all("div", class_=re.compile(r"c-field--name-field-(?:contact|ny-locations|icon)")):
        t.decompose()
    region = ""
    reg = main.find("div", class_=re.compile(r"c-field--name-field-ny-locations"))
    if reg is not None:
        region = clean(reg.get_text(" ").replace("This Page Covers", "").replace("Icon", ""))
    lines = [ln for ln in _text_lines(body) if ln != title and not ln.startswith("ENB Publish Date")]
    # labelled fields: "Label:" on its own line (or "Label: value") followed by value lines until the next label
    fields: dict[str, str] = {}
    free: list[str] = []
    i = 0
    while i < len(lines):
        ln = lines[i]
        label = None
        for lab in _LABELS:
            if ln.lower().startswith(lab.lower() + ":") or ln.lower() == lab.lower() + ":":
                label = lab
                break
        if label is None and re.match(r"^(?:For\s+\w[\w ]*:\s*)?[A-Z][A-Za-z()/, ]{2,40}:$", ln):
            label = ln.rstrip(":")
            label = re.sub(r"^For\s+\w[\w ]*:\s*", "", label)
        if label:
            value = [ln.split(":", 1)[1].strip()] if ":" in ln and ln.split(":", 1)[1].strip() else []
            i += 1
            while i < len(lines) and not re.match(r"^[A-Z(][A-Za-z()/, ]{2,40}:(?:\s|$)", lines[i]):
                value.append(lines[i])
                i += 1
            fields[label] = clean(" ".join(value))
            continue
        free.append(ln)
        i += 1
    category = free[0] if free else ""
    if re.search(r"renew the State Pollutant Discharge Elimination System", category, re.I):
        category = "SPDES permit renewal"
    elif len(category) > 80:
        category = "Notice"
    description = fields.get("Project Description") or " ".join(free[1:] if free and len(free[0]) <= 80 else free)
    county = None
    for key in ("County", "Project is Located", "Location", "Project Location"):
        if fields.get(key) and county_named(fields[key] + (" County" if key == "County" else "")):
            county = county_named(fields[key] + (" County" if key == "County" else ""))
            break
    if not county:
        county = county_named(" ".join(free[:3]))
    text = " ".join([title, category, description] + [f"{k}: {v}" for k, v in fields.items()])
    m = _TITLE_MUNI.match(title)
    muni, muni_kind, project = None, None, title
    munis: list[tuple[str, str]] = []
    if m:
        # "Town of Halfmoon - RIC Energy", "Village of Bainbridge and Town of Bainbridge - Water System"
        munis = municipalities(f"{m.group(1)} of {m.group(2)}")
        if not munis:
            kind = {"town": "town", "towns": "town", "city": "city", "cities": "city", "village": "village",
                    "villages": "village"}[m.group(1).lower()]
            munis = [(m.group(2).strip(), kind)]
        muni, muni_kind = munis[0]
        project = m.group(3).strip()
    else:
        m2 = _TITLE_OTHER.match(title)
        if m2:
            muni, muni_kind, project = m2.group(1), "other", m2.group(2).strip()
            munis = [(muni, "other")]
        elif fields.get("(C)ity, (T)own, or (V)illage"):
            mm = re.match(r"(Town|City|Village)\s+of\s+(.+)", fields["(C)ity, (T)own, or (V)illage"])
            if mm:
                muni, muni_kind = mm.group(2), mm.group(1).lower()
                munis = [(muni, muni_kind)]
    lead = None
    mla = _LEAD_AGENCY.search(" ".join(free[1:3]))
    if mla:
        lead = clean(mla.group(1))
    hearing_date, hearing_place = None, None
    for hm in _HEARING.finditer(text):
        ds = [d for d in parse_dates(hm.group(1)) if not pub or d >= pub]
        if ds:
            hearing_date = ds[0]
            pm = _PLACE.search(hm.group(1))
            hearing_place = clean(pm.group(1)) if pm else None
            break
    deadline = None
    for key in ("Deadline for Comments", "Comment Period Ends", "Written Comments Due"):
        if fields.get(key):
            deadline = parse_date(fields[key])
            break
    if not deadline:
        for dm in _DEADLINE_LINE.finditer(text):
            d = parse_date(dm.group(1))
            if d:
                deadline = d
                break
    topics = notice_topics(text)
    return {
        "title": title, "project": project, "publish_date": iso(pub), "kind": kind_of(url), "category": category,
        "municipality": muni, "municipality_kind": muni_kind, "municipalities": [{"name": n, "kind": k} for n, k in munis],
        "county": county, "region": region,
        "lead_agency": lead, "applicant": fields.get("Applicant") or fields.get("Permittee Name"),
        "facility": fields.get("Facility") or fields.get("Facility Name"),
        "permits": fields.get("Permit(s) Applied for"), "description": clean(description),
        "comment_deadline": iso(deadline), "hearing_date": iso(hearing_date), "hearing_place": hearing_place,
        "topics": topics, "siting_relevant": bool(topics), "link": url,
    }


def to_hits(item: dict, places: NYPlaces) -> list[dict]:
    """One hit per municipality the title names (usually one)."""
    if not item["siting_relevant"]:
        return []
    out = []
    for m in item.get("municipalities") or ([{"name": item["municipality"], "kind": item["municipality_kind"]}]
                                            if item.get("municipality") else []):
        h = to_hit({**item, "municipality": m["name"], "municipality_kind": m["kind"]}, places)
        if h and all(x["town"] != h["town"] for x in out):
            out.append(h)
    return out


def to_hit(item: dict, places: NYPlaces) -> dict | None:
    if not item["siting_relevant"] or not item.get("municipality"):
        return None
    kind = item["municipality_kind"] or "town"
    if kind == "other":
        town, _ = places.resolve(item["municipality"], "town")
        if not town:
            return None
    else:
        town, _ = places.resolve(item["municipality"], kind)
    if not town:
        return None
    if item.get("hearing_date"):
        when, date_kind = date.fromisoformat(item["hearing_date"]), "hearing"
    elif item.get("comment_deadline"):
        when, date_kind = date.fromisoformat(item["comment_deadline"]), "comment_deadline"
    else:
        when, date_kind = None, "notice"
    who = item.get("lead_agency") or item.get("applicant") or ""
    lead_in = f"{item['category']}" + (f", {item['county']} County" if item.get("county") else "")
    if len(item.get("municipalities") or []) > 1:
        lead_in += f", filed under {town}"       # one notice, several places: each hit needs its own id
    if who:
        lead_in += f". {who}"
    snippet = snippet_of(lead_in + ".", sentences(item["description"], 2))
    county = item.get("county") or places.row_county.get(town)
    return make_hit(
        source=SOURCE, source_kind=SOURCE_KIND, state=STATE, town=town, county=county, board=BOARD,
        meeting_date=when, date_kind=date_kind, topics=item["topics"], snippet=snippet, source_url=item["link"],
        listing_url=LISTING_URL, document_title=f"ENB {item['publish_date']}: {item['title']}",
        first_seen=item["first_seen"], headline_text=f"{item['title']}: {item['category']}",
        place=item.get("hearing_place"), comment_deadline=date.fromisoformat(item["comment_deadline"])
        if item.get("comment_deadline") else None,
        extra={"notice_date": item["publish_date"], "notice_kind": item["kind"], "lead_agency": item.get("lead_agency"),
               "attributed_from": None, "configured": places.configured(town) is not None})


# ------------------------------------------------------------------------------------------ run
def run(fetcher: PoliteFetcher, out_dir: Path, days: int = 30, data_dir: Path | None = None,
        today: date | None = None) -> dict:
    check_out_dir(out_dir)
    started = now_iso()
    since = window_start(days, today)
    places = NYPlaces(data_dir) if data_dir else NYPlaces()
    ledger = load_ledger(out_dir, SOURCE)
    errors: list[str] = []
    urls = notice_urls(fetcher, since, errors)
    log.info("%d ENB notices since %s in the sitemaps", len(urls), since)
    items: list[dict] = []
    skipped = 0
    for url, issue, _lastmod in urls[-MAX_NOTICES_PER_RUN:]:
        if not fetcher.allowed(url):
            skipped += 1
            errors.append(f"robots.txt disallows {url}")
            continue
        try:
            with fetcher.purpose("document"):
                r = fetcher.get(url, max_age=NOTICE_MAX_AGE)
        except RobotsDisallowed as e:
            skipped += 1
            errors.append(f"robots: {e}"[:200])
            continue
        except FetchError as e:
            errors.append(f"{url}: {e}"[:200])
            continue
        if not r.ok:
            errors.append(f"{url}: HTTP {r.status}")
            continue
        try:
            it = parse_notice(r.text, url)
        except Exception as e:  # noqa: BLE001 - one bad page must not stop the run
            errors.append(f"{url}: parse {e}"[:200])
            continue
        if not it["publish_date"]:
            it["publish_date"] = issue.isoformat()
        it["first_seen"] = first_seen(ledger, url, started)
        if it.get("municipality"):
            kind = it["municipality_kind"] if it["municipality_kind"] in ("town", "city", "village") else "town"
            site_name, configured = places.resolve(it["municipality"], kind)
            it["town"], it["town_configured"] = site_name, configured
        else:
            it["town"], it["town_configured"] = None, False
        items.append(it)
    # notices seen on earlier runs stay in the items file (the sitemap only looks back as far as `since`)
    prev = {i["link"]: i for i in (load_json_items(out_dir) or [])}
    for it in items:
        prev[it["link"]] = it
    all_items = sorted(prev.values(), key=lambda i: (i.get("publish_date") or "", i["link"]), reverse=True)
    hits = [h for i in all_items for h in to_hits(i, places)]
    report = {
        "source": SOURCE, "started": started, "finished": now_iso(), "since": since.isoformat(),
        "notice_urls_in_window": len(urls), "notices_read": len(items), "robots_skipped": skipped,
        "items_total": len(all_items), "relevant": sum(i["siting_relevant"] for i in items), "hits": len(hits),
        "issues": sorted({i["publish_date"] for i in items if i.get("publish_date")}),
        "kinds": dict(Counter(i["kind"] for i in items)),
        "categories": dict(Counter(i["category"] for i in items).most_common(20)),
        "topics": dict(Counter(t for i in items for t in i["topics"]).most_common()),
        "towns_unresolved": sorted({i["municipality"] for i in items if i.get("municipality") and not i.get("town")}),
        "errors": errors, "network": network_report(fetcher),
    }
    write_outputs(SOURCE, out_dir, all_items, hits, LISTING_URL, report, ledger)
    return report


def load_json_items(out_dir: Path) -> list[dict]:
    from .state_feeds import load_json
    return load_json(Path(out_dir) / f"{SOURCE}_items.json", {}).get("items", [])


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    p.add_argument("--cache-dir", type=Path, default=DEFAULT_CACHE_DIR)
    p.add_argument("--days", type=int, default=30, help="read notices published this many days back")
    p.add_argument("--offline", action="store_true", help="read the fetch cache only")
    p.add_argument("-v", "--verbose", action="store_true")
    a = p.parse_args(argv)
    logging.basicConfig(level=logging.DEBUG if a.verbose else logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    rep = run(PoliteFetcher(a.cache_dir, offline=a.offline), a.out_dir, a.days)
    print(f"ENB: {rep['notices_read']} notices read ({rep['notice_urls_in_window']} in the window), {rep['relevant']} relevant, "
          f"{rep['hits']} hits; topics {rep['topics']}; errors {len(rep['errors'])}; network {rep['network']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
